import { keepPreviousData, useMutation, useQuery, useQueryClient } from '@tanstack/react-query';

import { consoleKeys } from '@/features/console/queries';
import { isLatLng, type LatLng } from '@/lib/geo';
import { mappls } from '@/lib/mappls';
import { supabase } from '@/lib/supabase';

import {
  ilikeTerm,
  PAGE_SIZE,
  rangeStart,
  toLoadInsert,
  type AssignValues,
  type CreateLoadValues,
  type DateRange,
  type LoadStatus,
  type TripStatus,
} from './schemas';

export const loadKeys = {
  list: (f: LoadFilters) => ['loads', 'list', f] as const,
  detail: (id: string) => ['loads', 'detail', id] as const,
  trips: (f: TripFilters) => ['trips', 'list', f] as const,
  shippers: ['loads', 'shippers'] as const,
};

const pageRange = (page: number) => [page * PAGE_SIZE, page * PAGE_SIZE + PAGE_SIZE - 1] as const;

// ---------- C2 Loads (server-side filter, search, sort, pagination on the load_list view) ----------

export type LoadSort = 'created_at' | 'load_code' | 'planned_distance_m';
export interface LoadFilters {
  status: LoadStatus | 'all';
  q: string;
  range: DateRange;
  page: number;
  sort: LoadSort;
  dir: 'asc' | 'desc';
}

export function useLoadsPage(f: LoadFilters) {
  return useQuery({
    queryKey: loadKeys.list(f),
    placeholderData: keepPreviousData,
    queryFn: async () => {
      let query = supabase.from('load_list').select('*', { count: 'exact' });
      if (f.status !== 'all') query = query.eq('load_status', f.status);
      if (f.q.trim()) {
        const t = ilikeTerm(f.q);
        query = query.or(`load_code.ilike.${t},pickup_address.ilike.${t},drop_address.ilike.${t}`);
      }
      const start = rangeStart(f.range);
      if (start) query = query.gte('created_at', start);
      const [from, to] = pageRange(f.page);
      const { data, error, count } = await query
        .order(f.sort, { ascending: f.dir === 'asc', nullsFirst: false })
        .order('id')
        .range(from, to);
      if (error) throw error;
      return { rows: data, total: count ?? 0 };
    },
  });
}

// ---------- C4 Load detail ----------

export function useLoad(id: string | undefined) {
  return useQuery({
    queryKey: loadKeys.detail(id ?? ''),
    enabled: !!id,
    queryFn: async () => {
      const [load, trips] = await Promise.all([
        supabase
          .from('loads')
          .select(
            'id, load_code, pickup_address, pickup_lat, pickup_lng, pickup_radius_m, drop_address, drop_lat, drop_lng, drop_radius_m, planned_distance_m, material, weight_kg, notes, created_at, shipper:profiles!loads_shipper_id_fkey(full_name), creator:profiles!loads_created_by_fkey(full_name)',
          )
          .eq('id', id!)
          .maybeSingle(),
        supabase
          .from('trips')
          .select(
            'id, status, created_at, started_at, ended_at, tracked_distance_m, driver:profiles!trips_driver_id_fkey(id, full_name, phone), vehicle:vehicles(id, registration_no, vehicle_type)',
          )
          .eq('load_id', id!)
          .order('created_at', { ascending: false }),
      ]);
      if (load.error) throw load.error;
      if (trips.error) throw trips.error;
      return load.data ? { load: load.data, trips: trips.data } : null;
    },
  });
}

