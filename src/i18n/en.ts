/** 420 → "420 m", 1830 → "1.8 km", 396_400 → "396 km" */
const fmtKm = (m: number) => {
  if (m < 1000) return `${Math.round(m)} m`;
  const tenths = Math.round(m / 100) / 10;
  return `${tenths >= 10 ? Math.round(m / 1000) : tenths.toFixed(1)} km`;
};

